"""Retain each grammar's licence next to its vendored parser sources.

Downstream packagers consume ``parsers/<language>/`` (via the parser-sources
release bundle) as source, so every grammar directory must carry the licence
that covers it. Upstream LICENSE/COPYING/NOTICE files are copied from the
grammar subdirectory and the repository root. A grammar whose pinned source has
no such file gets a generated ``NOTICE`` built from the committed provenance
record (``sources/grammar_notices.json``) that ``build_grammar_notices.py``
maintains, so the SPDX identifier and evidence are the same ones the release
notices publish.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path
from typing import Any

from build_grammar_notices import _cache_hint, _is_license_name, _split_forge

NOTICES_PATH = Path(__file__).resolve().parent.parent / "sources" / "grammar_notices.json"
GENERATED_NOTICE = "NOTICE"


def has_license_file(target_dir: Path) -> bool:
    """Whether a vendored grammar directory holds a top-level licence file."""
    return target_dir.is_dir() and any(path.is_file() and _is_license_name(path.name) for path in target_dir.iterdir())


def _license_files(directory: Path) -> list[Path]:
    if not directory.is_dir():
        return []
    return sorted(path for path in directory.iterdir() if path.is_file() and _is_license_name(path.name))


def _copy_upstream(vendor_repo: Path, directory: str | None, target_dir: Path) -> list[str]:
    sources = (_license_files(vendor_repo / directory) if directory else []) + _license_files(vendor_repo)
    kept: list[str] = []
    for source in sources:
        destination = target_dir / source.name
        if destination.exists():
            if destination.read_bytes() == source.read_bytes():
                continue
            # ~keep The grammar subdirectory's own licence keeps the plain name; the
            # repository root's differing one still applies, so it is kept beside it.
            destination = target_dir / f"{source.name}.root"
        shutil.copyfile(source, destination)
        kept.append(destination.name)
    return kept


def _resolve_spdx(entry: dict[str, Any] | None, definition: dict[str, Any]) -> str:
    if entry and entry.get("spdx"):
        return entry["spdx"]
    if definition.get("license"):
        return definition["license"]
    split = _split_forge(definition["repo"]) if definition.get("repo") else None
    return _cache_hint(split[1] if split else None) or "NOASSERTION"


def render_notice(language_name: str, definition: dict[str, Any], notices: dict[str, Any]) -> str:
    """The generated NOTICE for a grammar whose pinned source has no licence file."""
    entry = notices.get("languages", {}).get(language_name)
    texts = notices.get("licenses", {})
    if definition.get("repo"):
        upstream = f"Upstream: {definition['repo']} @ {definition.get('rev') or definition.get('branch') or 'HEAD'}"
    else:
        upstream = f"Source: in-repo {definition.get('local')}"
    lines = [
        f"Generated by tree-sitter-language-pack: the pinned upstream source of the `{language_name}`",
        "grammar carries no LICENSE, COPYING or NOTICE file. The licence below is recorded in",
        "sources/grammar_notices.json and the GRAMMAR_NOTICES-<version>.md release asset.",
        "",
        f"Language: {language_name}",
        upstream,
    ]
    if definition.get("directory"):
        lines.append(f"Directory: {definition['directory']}")
    lines.append(f"SPDX-License-Identifier: {_resolve_spdx(entry, definition)}")
    retained: list[str] = []
    if entry:
        lines.append(f"Resolution: {entry.get('resolution')} (SPDX source: {entry.get('spdx_source')})")
        for item in entry.get("license_files", []):
            lines.append(f"Evidence: {item['path']} (sha256 {item['sha256']})")
            text = texts.get(item["sha256"])
            if text and _is_license_name(Path(item["path"]).name):
                retained.append(text)
    body = "\n".join(lines) + "\n"
    return body + "".join(f"\n{text}" for text in retained)


def retain_licenses(
    language_name: str,
    definition: dict[str, Any],
    vendor_repo: Path,
    target_dir: Path,
    *,
    notices_path: Path = NOTICES_PATH,
) -> list[str]:
    """Copy the grammar's licence files into ``target_dir``; return the names written."""
    for stale in _license_files(target_dir):
        stale.unlink()
    kept = _copy_upstream(vendor_repo, definition.get("directory"), target_dir)
    if kept:
        return sorted(kept)
    notices = json.loads(notices_path.read_text(encoding="utf-8")) if notices_path.is_file() else {}
    (target_dir / GENERATED_NOTICE).write_text(render_notice(language_name, definition, notices), encoding="utf-8")
    return [GENERATED_NOTICE]
