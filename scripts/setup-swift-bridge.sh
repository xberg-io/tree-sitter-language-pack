#!/bin/bash

set -e

PROFILE="${1:-release}"
BUILD_DIR="target/${PROFILE}/build"

if stat -f '%m %N' "$BUILD_DIR" >/dev/null 2>&1; then
  STAT_FMT=(-f '%m %N')
else
  STAT_FMT=(-c '%Y %n')
fi
OUT=$(find "$BUILD_DIR" -maxdepth 2 -type d -name out -path '*tree-sitter-language-pack-swift-*' \
  -exec stat "${STAT_FMT[@]}" {} + 2>/dev/null | sort -rn | head -1 | cut -d' ' -f2-)
if [ -z "$OUT" ]; then
  echo "ERROR: Could not find swift-bridge build output in ${BUILD_DIR}/"
  exit 1
fi

echo "Using swift-bridge output from: $OUT"

mkdir -p packages/swift/Sources/RustBridgeC
mkdir -p packages/swift/Sources/RustBridge

# RustBridgeC.h is normally materialized by `alef generate`, which wraps the raw
# swift-bridge concatenation in an include guard and a provenance header. CI and
# `mise run swift:bridge` invoke this script directly instead (no alef run in between),
# so it must reproduce alef's exact wrapping byte-for-byte: on a clean tree, where
# the committed header already reflects the current Rust API, this keeps the write
# a no-op instead of stripping the guard and dropping provenance. ~keep
{
  printf '#ifndef RUST_BRIDGE_C_H\n#define RUST_BRIDGE_C_H\n\n'
  printf '// Auto-generated by alef \xe2\x80\x94 do not edit by hand.\n'
  printf '// Concatenates SwiftBridgeCore.h and tree-sitter-language-pack-swift.h produced by\n'
  # shellcheck disable=SC2016  # backticks are literal in the emitted C comment; expanding breaks it. ~keep
  printf '// `cargo build -p tree-sitter-language-pack-swift` via swift_bridge_build.\n\n'
  cat "$OUT/SwiftBridgeCore.h" "$OUT/tree-sitter-language-pack-swift/tree-sitter-language-pack-swift.h"
  printf '#endif /* RUST_BRIDGE_C_H */\n'
} >packages/swift/Sources/RustBridgeC/RustBridgeC.h

{
  printf 'import RustBridgeC\n'
  cat "$OUT/SwiftBridgeCore.swift"
} >packages/swift/Sources/RustBridge/SwiftBridgeCore.swift
{
  printf 'import RustBridgeC\n'
  cat "$OUT/tree-sitter-language-pack-swift/tree-sitter-language-pack-swift.swift"
} >packages/swift/Sources/RustBridge/tree-sitter-language-pack-swift.swift

echo "Swift-bridge files setup complete"
